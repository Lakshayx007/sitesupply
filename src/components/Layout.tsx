import { ExternalLink, Menu, X } from "lucide-react";
import type { MouseEvent } from "react";
import { useEffect, useState } from "react";
import { NavLink, Outlet, useLocation } from "react-router-dom";
import { SITE } from "../config";
import { useDb } from "../db/DbProvider";
import { Logo } from "./Logo";
import { SampleDataPill } from "./SampleDataPill";
import { ThemeToggle } from "./ThemeToggle";

const DEMO = [{ to: "/demo", label: "Demo" }];
const PM = [
  { to: "/vendors", label: "Vendors" },
  { to: "/dashboard", label: "Dashboard" },
  { to: "/insights", label: "Insights" },
  { to: "/stats-lab", label: "Stats Lab" },
  { to: "/docs", label: "Docs" },
  { to: "/method", label: "Method" },
];

const linkClass = ({ isActive }: { isActive: boolean }) =>
  `rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
    isActive ? "bg-primary/10 text-primary-ink" : "text-muted hover:bg-subtle hover:text-ink"
  }`;

function Header() {
  const [open, setOpen] = useState(false);
  const { pathname } = useLocation();

  // Close the mobile menu on navigation.
  useEffect(() => setOpen(false), [pathname]);

  return (
    <header className="sticky top-0 z-40 border-b border-border bg-surface/90 backdrop-blur supports-[backdrop-filter]:bg-surface/75">
      <div className="mx-auto flex h-16 max-w-page items-center gap-3 px-4 sm:px-6">
        <Logo />
        <SampleDataPill className="ml-1" />

        <nav aria-label="Main" className="ml-auto hidden items-center gap-1 lg:flex">
          {DEMO.map((l) => (
            <NavLink key={l.to} to={l.to} className={linkClass}>
              {l.label}
            </NavLink>
          ))}
          <span className="mx-2 h-5 w-px bg-border" aria-hidden="true" />
          {PM.map((l) => (
            <NavLink key={l.to} to={l.to} className={linkClass}>
              {l.label}
            </NavLink>
          ))}
        </nav>

        <div className="ml-auto flex items-center gap-2 lg:ml-2">
          <ThemeToggle />
          <button
            type="button"
            className="inline-flex h-9 w-9 items-center justify-center rounded-xl border border-border text-ink hover:bg-subtle lg:hidden"
            aria-label={open ? "Close menu" : "Open menu"}
            aria-expanded={open}
            aria-controls="mobile-nav"
            onClick={() => setOpen((o) => !o)}
          >
            {open ? <X aria-hidden="true" className="h-5 w-5" /> : <Menu aria-hidden="true" className="h-5 w-5" />}
          </button>
        </div>
      </div>

      {open && (
        <nav id="mobile-nav" aria-label="Main" className="border-t border-border bg-surface px-4 pb-4 pt-2 lg:hidden">
          <p className="eyebrow px-3 pb-1 pt-2">Product demo</p>
          <div className="flex flex-col">
            {DEMO.map((l) => (
              <NavLink key={l.to} to={l.to} className={linkClass}>
                Orders, detail and alert
              </NavLink>
            ))}
          </div>
          <p className="eyebrow px-3 pb-1 pt-3">PM workspace</p>
          <div className="flex flex-col">
            {PM.map((l) => (
              <NavLink key={l.to} to={l.to} className={linkClass}>
                {l.label}
              </NavLink>
            ))}
          </div>
        </nav>
      )}
    </header>
  );
}

function Footer() {
  return (
    <footer className="mt-16 border-t border-border bg-subtle">
      <div className="mx-auto grid max-w-page gap-6 px-4 py-10 sm:px-6 md:grid-cols-[1fr_auto] md:items-end">
        <div className="max-w-2xl space-y-2">
          <Logo />
          <p className="text-sm text-muted">
            <strong className="font-semibold text-ink">All data on this site is sample data.</strong> It was generated by a
            program (<code className="text-[13px]">scripts/make_sample_data.py</code>, seed 42) for {SITE.dataWindow}, with some
            patterns planted on purpose. It does not describe any real company, vendor or customer. Vendors are named Vendor A
            to Vendor L.
          </p>
          <p className="text-sm text-muted">A product-management portfolio project by {SITE.author}.</p>
        </div>
        <div className="flex flex-wrap items-center gap-3 text-sm">
          <NavLink to="/method" className="link">
            How the data was made
          </NavLink>
          <a href={SITE.githubUrl} className="btn-secondary" target="_blank" rel="noreferrer">
            GitHub
            <ExternalLink aria-hidden="true" className="h-4 w-4" />
            <span className="sr-only">(opens in a new tab)</span>
          </a>
        </div>
      </div>
    </footer>
  );
}

function DbStatusBanner() {
  const { status, error } = useDb();
  if (status !== "error") return null;
  return (
    <div role="alert" className="border-b border-status-late/40 bg-status-late/10 px-4 py-3 text-sm text-status-late-ink">
      <div className="mx-auto max-w-page sm:px-2">
        The sample database could not be loaded: {error.message} Try refreshing the page.
      </div>
    </div>
  );
}

function skipToMain(e: MouseEvent<HTMLAnchorElement>) {
  e.preventDefault();
  document.getElementById("main")?.focus();
}

export function Layout() {
  const { pathname } = useLocation();
  useEffect(() => {
    window.scrollTo(0, 0);
  }, [pathname]);

  return (
    <div className="flex min-h-screen flex-col">
      {/* HashRouter owns the URL hash, so the skip link moves focus instead of changing the hash. */}
      <a href="#main" className="skip-link btn-primary" onClick={skipToMain}>
        Skip to content
      </a>
      <Header />
      <DbStatusBanner />
      <main id="main" tabIndex={-1} className="flex-1 focus:outline-none">
        <Outlet />
      </main>
      <Footer />
    </div>
  );
}
